inline void drawMediumGlyph(DisplayDriver& display, int x, int y, const uint8_t rows[12]) {
  for (int dy = 0; dy < 12; ++dy) {
    for (int dx = 0; dx < 8; ++dx) {
      if (rows[dy] & (1 << dx)) display.fillRect(x + dx, y + dy, 1, 1);
    }
  }
}

inline void drawStationMediumText(DisplayDriver& display, int x, int y, const char* text) {
  while (*text) {
    unsigned char c = static_cast<unsigned char>(*text++);
    if (c < 32 || c > 126) c = '?';
    drawMediumGlyph(display, x, y, stationMediumGlyphs[c - 32]);
    x += 8;
  }
}
